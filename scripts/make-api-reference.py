#!/usr/bin/env python3
"""Renders the public API reference in docs/ARCHITECTURE.md section 11.

Reads the symbol graphs written by `swift package dump-symbol-graph` and
replaces the region between the generated-region markers in the document.
Run it through scripts/make-api-reference.sh, which dumps the graphs first.

Usage: python3 -I scripts/make-api-reference.py --graphs DIR [--check]

Exit status: 0 when the document is current or was written, 1 when --check
finds it stale, 2 on an error.
"""

import argparse
import difflib
import json
import re
import sys
from pathlib import Path
from urllib.parse import unquote, urlparse

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs/ARCHITECTURE.md"
BEGIN_MARKER = "<!-- generated by scripts/make-api-reference.sh; do not edit -->"
END_MARKER = "<!-- end generated -->"
INDENT = "    "

# Files are listed by layer, top to bottom; unlisted directories follow by path.
LAYER_ORDER = [
    "Sources/RESP/",
    "Sources/RedisClient/",
    "Sources/Formatters/",
    "Sources/CommandSpecs/",
    "Sources/RedisCore/",
    "Sources/RedisUI/",
    "Sources/Features/",
    "Sources/AppShell/",
    "Tests/TestSupport/",
]
IMPLIED_CONFORMANCES = {"Copyable", "Escapable", "SendableMetatype"}
PARENT_KINDS = {"memberOf", "requirementOf", "optionalRequirementOf"}
MAIN_ACTOR = "@MainActor "
LEADING_ATTRIBUTES = re.compile(r"^(?:@\w+(?:\([^)]*\))? )+")


class Symbol:
    def __init__(self, raw, path):
        self.id = raw["identifier"]["precise"]
        self.kind = raw["kind"]["identifier"]
        self.path_components = raw["pathComponents"]
        spelling = "".join(f["spelling"] for f in raw.get("declarationFragments", []))
        self.declaration = re.sub(r"\s*\n\s*", " ", spelling).strip()
        position = raw["location"]["position"]
        self.file = path
        self.position = (position["line"], position["character"])
        extension = raw.get("swiftExtension")
        self.in_extension = extension is not None
        extension = extension or {}
        self.extension_constraints = [_constraint(c) for c in extension.get("constraints", [])]
        generics = raw.get("swiftGenerics", {})
        self.own_constraints = [_constraint(c) for c in generics.get("constraints", [])]
        self.parent_id = None
        self.parent_fallback = None
        self.default_implementation_of = None
        self.conformances = set()
        self.children = []

    @property
    def is_extension_block(self):
        return self.kind == "swift.extension"

    @property
    def is_main_actor(self):
        return self.declaration.startswith(MAIN_ACTOR)

    @property
    def qualified_name(self):
        return ".".join(self.path_components)

    def sort_key(self):
        return (self.position, self.declaration)


def _constraint(raw):
    operator = " == " if raw["kind"] == "sameType" else ": "
    return f"{raw['lhs']}{operator}{raw['rhs']}"


def _where(constraints):
    return f" where {', '.join(constraints)}" if constraints else ""


def _repo_path(uri):
    parsed = urlparse(uri)
    if parsed.scheme != "file":
        return None
    path = Path(unquote(parsed.path))
    try:
        relative = path.resolve().relative_to(ROOT)
    except ValueError:
        return None
    return relative.as_posix() if path.exists() else None


def load_symbols(graph_dir):
    symbols = {}
    relationships = []
    for graph in sorted(graph_dir.glob("*.symbols.json")):
        data = json.loads(graph.read_text(encoding="utf-8"))
        for raw in data.get("symbols", []):
            location = raw.get("location")
            if not location or raw["identifier"]["precise"] in symbols:
                continue
            path = _repo_path(location["uri"])
            if path is not None:
                symbols[raw["identifier"]["precise"]] = Symbol(raw, path)
        relationships.extend(data.get("relationships", []))
    return symbols, relationships


def link(symbols, relationships):
    for rel in relationships:
        source = symbols.get(rel["source"])
        if source is None:
            continue
        if rel["kind"] in PARENT_KINDS and source.parent_id is None:
            source.parent_id = rel["target"]
            source.parent_fallback = rel.get("targetFallback")
        elif rel["kind"] == "defaultImplementationOf":
            source.default_implementation_of = rel["target"]
        elif rel["kind"] == "conformsTo":
            target = symbols.get(rel["target"])
            if target is not None:
                name = target.qualified_name
            else:
                name = rel.get("targetFallback", rel["target"]).split(".", 1)[-1]
            if name not in IMPLIED_CONFORMANCES:
                source.conformances.add(name)
    for symbol in symbols.values():
        requirement = symbols.get(symbol.default_implementation_of)
        if symbol.parent_id is None and requirement is not None:
            symbol.parent_id = requirement.parent_id


def type_line(symbol):
    declaration = symbol.declaration
    if not symbol.conformances:
        return declaration
    conformances = ": " + ", ".join(sorted(symbol.conformances))
    head, separator, tail = declaration.partition(" where ")
    return head + conformances + separator + tail


class ExtensionGroup:
    def __init__(self, header, position, is_main_actor):
        self.header = header
        self.position = position
        self.is_main_actor = is_main_actor
        self.children = []

    def sort_key(self):
        return (self.position, self.header)


def build_files(symbols):
    files = {}
    groups = {}

    def entries(path):
        return files.setdefault(path, [])

    for symbol in symbols.values():
        parent = symbols.get(symbol.parent_id) if symbol.parent_id else None
        if symbol.parent_id is None:
            entries(symbol.file).append(symbol)
            continue

        if parent is not None and parent.is_extension_block:
            extra = parent.extension_constraints
        else:
            inherited = parent.own_constraints if parent is not None else []
            extra = [c for c in symbol.extension_constraints if c not in inherited]
        protocol_extension = parent is not None and parent.kind == "swift.protocol" and symbol.in_extension
        same_file = parent is not None and parent.file == symbol.file
        if same_file and (parent.is_extension_block or not (extra or protocol_extension)):
            parent.children.append(symbol)
            continue

        if parent is not None:
            name = parent.qualified_name
        else:
            name = (symbol.parent_fallback or symbol.parent_id).split(".", 1)[-1]
        header = f"extension {name}{_where(extra)}"
        key = (symbol.file, symbol.parent_id, header)
        group = groups.get(key)
        if group is None:
            is_main_actor = parent is not None and parent.is_main_actor
            group = groups[key] = ExtensionGroup(header, symbol.position, is_main_actor)
            entries(symbol.file).append(group)
        group.position = min(group.position, symbol.position)
        group.children.append(symbol)
    return files


def render_entry(entry, depth, lines, in_main_actor=False):
    if isinstance(entry, ExtensionGroup):
        lines.append(INDENT * depth + entry.header)
    else:
        line = type_line(entry)
        attributes = LEADING_ATTRIBUTES.match(line)
        if in_main_actor and attributes:
            prefix = attributes.group(0).replace(MAIN_ACTOR, "")
            line = prefix + line[attributes.end() :]
        lines.append(INDENT * depth + line)
    for child in sorted(entry.children, key=lambda c: c.sort_key()):
        render_entry(child, depth + 1, lines, in_main_actor or entry.is_main_actor)


def file_order(path):
    for rank, prefix in enumerate(LAYER_ORDER):
        if path.startswith(prefix):
            return (rank, path)
    return (len(LAYER_ORDER), path)


def render(files):
    blocks = []
    for path in sorted(files, key=file_order):
        lines = []
        for entry in sorted(files[path], key=lambda e: e.sort_key()):
            render_entry(entry, 0, lines)
        blocks.append(f"### `{path}`\n\n```swift\n" + "\n".join(lines) + "\n```\n")
    return "\n".join(blocks)


def fail(message):
    print(f"make-api-reference: {message}", file=sys.stderr)
    sys.exit(2)


def splice(document, generated):
    begin = document.find(BEGIN_MARKER)
    end = document.find(END_MARKER)
    if begin < 0 or end < begin:
        fail(f"{DOC.relative_to(ROOT)} has no '{BEGIN_MARKER}' ... '{END_MARKER}' region")
    head = document[: begin + len(BEGIN_MARKER)]
    return f"{head}\n\n{generated}\n{document[end:]}"


def main():
    parser = argparse.ArgumentParser(description="Render the public API reference into docs/ARCHITECTURE.md.")
    parser.add_argument("--graphs", type=Path, required=True, help="directory of *.symbols.json files")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 when the document would change")
    args = parser.parse_args()

    symbols, relationships = load_symbols(args.graphs)
    if not symbols:
        fail(f"no symbols found in {args.graphs}")
    link(symbols, relationships)
    generated = render(build_files(symbols))

    current = DOC.read_text(encoding="utf-8")
    updated = splice(current, generated)
    if updated == current:
        print(f"{DOC.relative_to(ROOT)} is up to date")
        return 0
    if args.check:
        name = str(DOC.relative_to(ROOT))
        diff = difflib.unified_diff(
            current.splitlines(keepends=True),
            updated.splitlines(keepends=True),
            fromfile=f"a/{name}",
            tofile=f"b/{name}",
        )
        sys.stdout.writelines(diff)
        print(f"{name} is out of date; run scripts/make-api-reference.sh", file=sys.stderr)
        return 1
    DOC.write_text(updated, encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
