#!/usr/bin/env bash
set -euo pipefail

# Regenerates the public API reference in docs/ARCHITECTURE.md section 11.
# Usage: scripts/make-api-reference.sh [--check]

SCRATCH_PATH=".build/dev"

usage() {
  cat <<'USAGE'
Usage: scripts/make-api-reference.sh [--check]

Dumps the package's public symbol graphs and rewrites the generated region of
docs/ARCHITECTURE.md section 11 (between the "generated by" and "end generated"
markers).

  --check      write nothing; print a diff and exit 1 when the section is stale
  -h, --help   show this help

Exit status: 0 when the section is current or was rewritten, 1 when --check
finds it stale, 2 on an error.
USAGE
}

die() {
  printf 'make-api-reference.sh: %s\n' "$*" >&2
  exit 2
}

require_cmd() {
  command -v "$1" >/dev/null 2>&1 || die "'$1' is required but not installed."
}

check=false
while (($#)); do
  case "$1" in
    --check) check=true ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      usage >&2
      exit 2
      ;;
  esac
  shift
done

require_cmd swift
require_cmd python3

cd "$(dirname "$0")/.."

if ! dump_output="$(swift package --scratch-path "$SCRATCH_PATH" dump-symbol-graph \
  --minimum-access-level public \
  --skip-synthesized-members \
  --emit-extension-block-symbols 2>&1)"; then
  printf '%s\n' "$dump_output" >&2
  die "swift package dump-symbol-graph failed"
fi

graphs_dir="$(sed -n 's/^Files written to //p' <<<"$dump_output" | tail -n 1)"
[[ -d "$graphs_dir" ]] || die "could not find the symbol graph directory in the dump-symbol-graph output"

render_args=(--graphs "$graphs_dir")
if [[ "$check" == true ]]; then
  render_args+=(--check)
fi
python3 -I scripts/make-api-reference.py "${render_args[@]}"
